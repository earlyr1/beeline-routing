/** Подсказка к метке: что именно бригада везёт с собой по такой заявке. */
export const EQUIPMENT_TITLE = 'Нужно привезти оборудование: роутер, приставка или колонка';

/**
 * Метка заявки, к которой инженер берёт с собой единицу оборудования.
 * Цвет спокойный: это не срочность, но на план метка влияет — такая заявка тратит единицу дневного
 * запаса бригады, и без свободной единицы исполнителя ей не найдут.
 */
export function EquipmentBadge() {
  return (
    <span className="badge badge--equipment" title={EQUIPMENT_TITLE}>
      Оборудование
    </span>
  );
}
